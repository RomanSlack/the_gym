"""Export the site terrain + water for the 2D drawings (blueprint/).

Writes model/site_terrain.json: a 2 m grid over ±240 m, heights and water levels
in cm relative to ±0.00 (water null where dry). Committed, so every version of the
drawings has its own terrain for replay.

.venv/bin/python export_blueprint.py
"""
import json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RV = ROOT / "terrain" / "out" / "ravine"
HALF, STEP = 240, 2

H = np.load(RV / "eroded_1m.npy")
W = np.load(RV / "water_1m.npy")
sl = slice(1000 - HALF, 1000 + HALF)
h = H[sl, sl].reshape(HALF, 2, HALF, 2).mean((1, 3))
w = W[sl, sl].reshape(HALF, 2, HALF, 2)
wet = ~np.isnan(w).any((1, 3))
wl = np.where(wet, np.nanmean(w, axis=(1, 3)), np.nan)
out = {
    "note": "Generated by terrain/export_blueprint.py from terrain/out/ravine/eroded_1m.npy. Row 0 = south.",
    "origin": [-HALF + STEP / 2, -HALF + STEP / 2], "step": STEP, "nx": HALF, "ny": HALF, "unit": "cm",
    "heights": [int(round(v * 100)) for v in h.ravel()],
    "water": [None if np.isnan(v) else int(round(v * 100)) for v in wl.ravel()],
}
# wide, coarse grid for the site plan (the trail loop reaches ~900 m north)
WS = 10
hw = H[:2000, :2000].reshape(200, WS, 200, WS).mean((1, 3))
out["wide"] = {"origin": [-1000 + WS / 2, -1000 + WS / 2], "step": WS, "nx": 200, "ny": 200,
               "heights": [int(round(v * 100)) for v in hw.ravel()]}
(ROOT / "model" / "site_terrain.json").write_text(json.dumps(out, separators=(",", ":")))
print("wrote", (ROOT / "model" / "site_terrain.json").stat().st_size // 1024, "KB")
